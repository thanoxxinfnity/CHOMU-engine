#!/usr/bin/env python3
"""CHoMU 1.3: embed the editor GDScript plugins into the editor binary.
Writes godot/editor/chomu/chomu_store_data.h: a table of {name, data, size} written to
<editor data dir>/chomu_store/ at editor start (see editor/editor_node.cpp)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [  # (name in data dir, source)
    ('chomu_store.gd', os.path.join(HERE, 'chomu_store', 'chomu_store.gd')),
    ('chomu_graphics.gd', os.path.join(HERE, 'chomu_store', 'chomu_graphics.gd')),
    ('chomu_looks.gd', os.path.join(HERE, 'chomu_store', 'chomu_looks.gd')),
]
OUT = '/workspace/work/chomu-engine/godot/editor/chomu/chomu_store_data.h'
parts = ['/* Generated by branding/v1.3/gen_headers.py - CHoMU editor plugins (GDScript). */\n#pragma once\n\n']
names = []
for i, (name, src) in enumerate(FILES):
    if not os.path.exists(src):
        continue
    data = open(src, 'rb').read()
    parts.append(f'static const unsigned char chomu_store_file_{i}[] = {{{",".join(str(b) for b in data)}}};\n')
    names.append((name, i, len(data)))
parts.append('struct ChomuStoreFile { const char *name; const unsigned char *data; int size; };\n')
parts.append('static const ChomuStoreFile chomu_store_files[] = {\n')
for name, i, n in names:
    parts.append(f'\t{{ "{name}", chomu_store_file_{i}, {n} }},\n')
parts.append('};\n')
parts.append(f'static const int chomu_store_file_count = {len(names)};\n')
new = ''.join(parts)
old = open(OUT).read() if os.path.exists(OUT) else ''
if old != new:
    open(OUT, 'w').write(new)
print(OUT, [(n, s) for n, _, s in names], '(updated)' if old != new else '(unchanged)')
